#!/usr/bin/env bash
#
# Практическая работа 4. Вариант 5. Задача 3.
# ------------------------------------------------------------------
# Условие:
#   Определить количество (не подкаталогов и не ссылок) файлов
#   в каталоге /student.
#
# Пояснение:
#   Нужны ТОЛЬКО обычные файлы: без каталогов и без символических ссылок.
#   В find признак "-type f" отбирает именно обычные файлы: каталоги имеют
#   тип d, символические ссылки — тип l, поэтому они в выборку не попадают
#   (условие "! -type l" добавлено явно для наглядности, оно избыточно).
#   -maxdepth 1 ограничивает поиск самим каталогом /student (без обхода
#   вложенных подкаталогов), как и в формулировках про "подкаталоги в /student"
#   у других вариантов. wc -l считает число найденных строк = число файлов.
# ------------------------------------------------------------------
set -eu

DIR="${1:-/student}"

echo "Каталог: $DIR"
echo -n "Количество обычных файлов (не каталогов, не ссылок): "
find "$DIR" -maxdepth 1 -type f ! -type l | wc -l

