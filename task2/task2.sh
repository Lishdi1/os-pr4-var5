#!/usr/bin/env bash
#
# Практическая работа 4. Вариант 5. Задача 2.
# ------------------------------------------------------------------
# Условие:
#   Из информации, содержащейся в файлах query[1-5], определить ТОВАР,
#   которого было заказано наибольшее количество экземпляров в одном заказе.
#
# Инструменты: tr, sort, head, cut, grep, sed  (awk запрещён).
#
# Реальная структура файлов (база «JOCKSPORTS»):
#   query5 — позиции заказов, поля через пробел:
#       <поз> <N_заказа> <код_товара> <цена> <КОЛИЧЕСТВО> <сумма>
#        1      2          3           4       5           6
#   query3 — каталог товаров, поля через '!':
#       <код_товара>!<название>!<цена1>!<цена2>!<дата>
#   (файлы в кодировке с CRLF — символы '\r' убираются перед обработкой).
#
# Логика:
#   1) В query5 по полю 5 (количество) находим максимум.
#   2) Выбираем все позиции с этим количеством (возможна ничья).
#   3) По коду товара (поле 3) берём название из query3.
#
# Запуск:  ./task2.sh [каталог_с_query-файлами]   (по умолчанию — текущий каталог)
# ------------------------------------------------------------------
set -eu

DIR="${1:-.}"
Q5="$DIR/query5"
Q3="$DIR/query3"
for f in "$Q5" "$Q3"; do
  [ -r "$f" ] || { echo "Не найден файл: $f" >&2; exit 1; }
done

# Нормализованный query5: без CR, одиночные пробелы, без ведущих пробелов.
norm5=$(tr -d '\r' < "$Q5" | tr -s ' ' | sed 's/^ *//')

# 1) Максимальное количество экземпляров (поле 5).
maxqty=$(printf '%s\n' "$norm5" | sort -t' ' -k5,5 -nr | head -n1 | cut -d' ' -f5)

echo "Максимальное количество экземпляров товара в одном заказе: $maxqty"
echo "Позиции заказов с этим количеством:"
echo

# 2) Все позиции, где ПОЛЕ 5 равно максимуму.
#    Регулярное выражение пропускает ровно 4 поля и требует точного совпадения 5-го.
qre=$(printf '%s\n' "$maxqty" | sed 's/\./\\./g')
printf '%s\n' "$norm5" \
  | grep "^[^ ]* [^ ]* [^ ]* [^ ]* ${qre} " \
  | while read -r pos ord code price qty rest; do
      name=$(tr -d '\r' < "$Q3" | grep "^${code}!" | head -n1 | cut -d'!' -f2 | sed 's/ *$//')
      echo "    заказ № ${ord}: товар «${name}» (код ${code}) — ${qty} шт."
    done

echo
echo "ОТВЕТ: наибольшее количество экземпляров в одном заказе — ${maxqty} шт."
echo "       (перечисленные выше товары заказаны в этом количестве)."
