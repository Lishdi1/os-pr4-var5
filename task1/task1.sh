#!/usr/bin/env bash
#
# Практическая работа 4. Вариант 5. Задача 1.
# ------------------------------------------------------------------
# Условие:
#   В созданном текстовом файле оставить в каждой строке не более двух слов.
#   Слова, выходящие за этот предел, поместить в отдельный файл.
#   - В ПЕРВОМ файле-результате в тех строках, которые содержат менее двух
#     слов, в конец строки должен быть добавлен символ '='.
#   - Во ВТОРОМ файле-результате пустых строк оставаться не должно, а перед
#     непустыми строками должны быть указаны их номера в исходном файле,
#     отделённые от остального текста одним пробелом.
#   Результат сохранить в новых файлах, исходный файл остаётся без изменения.
#
# Инструменты: sed, nl (awk в этой работе использовать запрещено).
# Запуск:  ./task1.sh [исходный_файл]      (по умолчанию input.txt)
# ------------------------------------------------------------------
set -eu

SRC="${1:-input.txt}"
R1="result1.txt"   # не более двух слов в строке; '=' там, где слов меньше двух
R2="result2.txt"   # вынесенный остаток (3-е слово и далее) с номерами строк

# --- Первый файл-результат -----------------------------------------
# 1) Усечь каждую строку до первых двух слов.
#    Шаблон срабатывает только если за вторым словом есть пробел и ещё текст,
#    т.е. в строке >=3 слов. Строки с <=2 слов остаются без изменения.
# 2) К строкам, где меньше двух слов (в строке нет пробела -> 0 или 1 слово),
#    дописать '=' в конец.
sed -e 's/^\([^ ]\{1,\}\) \([^ ]\{1,\}\) .*/\1 \2/' "$SRC" \
  | sed '/ /!s/$/=/' > "$R1"

# --- Второй файл-результат -----------------------------------------
# nl -ba нумерует ВСЕ строки (номер == номер строки в исходном файле).
# Шаблон "номер слово1 слово2 <остаток>" печатается (флаг p) только для строк,
# где остаток есть (>=3 слов). Строки с <=2 слов не печатаются -> пустых строк нет.
nl -ba -w1 -s' ' "$SRC" \
  | sed -n 's/^\([0-9]\{1,\}\) [^ ]\{1,\} [^ ]\{1,\} \(.*\)/\1 \2/p' > "$R2"

echo "Исходный файл '$SRC' не изменён."
echo "  $R1 — строки не более чем из двух слов ('=' добавлен там, где слов меньше двух)"
echo "  $R2 — вынесенные лишние слова с номерами исходных строк"
